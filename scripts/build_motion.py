"""Extract the user's standalone motion engine without its demo life simulation.

Replicant Motion.html remains the authored source. The desktop owns physics,
behavior selection and soma state; this module only composes anatomy poses.
"""
from pathlib import Path
import hashlib

ROOT = Path(__file__).resolve().parents[1]


def compile_motion():
    source = (ROOT / 'assets' / 'motion' / 'Replicant Motion.html').read_text(encoding='utf-8')
    start = source.index('  const MASK =')
    end = source.index('  // Exposed for tooling and tests', start)
    code = '\n'.join(line[2:] if line.startswith('  ') else line for line in source[start:end].splitlines())
    digest = hashlib.sha256(source.encode()).hexdigest()
    # Keep the actual desktop-demo pose function and its transitions. Do not
    # approximate these in the overlay renderer: walk uses step, not wall time.
    life_start = source.index('  const clamp = (v, lo, hi)')
    life_end = source.index('  const ENERGY_GAIN =', life_start)
    pose_start = source.index('  const NOBLINK =', life_end)
    pose_end = source.index('  function fitStage()', pose_start)
    life_code = source[life_start:life_end] + source[pose_start:pose_end]
    # Preserve authored poses/transitions. Live soma owns behavior selection.
    spending = ' else if (["hop", "dance", "cheer", "jacks", "lift", "cartwheel", "skip"].includes(s)) L.energy = Math.max(0, L.energy - 0.05);'
    assert spending in life_code
    life_code = life_code.replace(spending, '')
    weights_start = life_code.index('  // How likely each animation')
    impact_start = life_code.index('  function impact(', weights_start)
    life_code = life_code[:weights_start] + life_code[impact_start:]
    life_code = life_code.replace('Math.random()', 'random()')
    factory = '''
// Authored start/impact/lifePose, with host geometry and soma behavior selection.
// The demo's synthetic energy spending and weighted selector are excluded.
function createLifeMotion(random = Math.random) {
  let SW = 320;
  const pointer = { x: -999, y: -999, inside: false };
  const life = [];
  const safeRange = (pl) => [pl.x0 - OX - 1, pl.x1 - OX - 6];
''' + life_code + '''
  return { start, impact, pose: lifePose, AFTER,
    configure(width, cursor) { SW = width; Object.assign(pointer, cursor); },
    register(body) { life.push(body); },
  };
}
'''
    target = ROOT / 'desktop/src/motion.js'
    target.write_text(
        '// Generated by scripts/build_motion.py from Replicant Motion.html.\n'
        f'// Source SHA256: {digest}\n'
        + code + factory + '\nexport { MASK, AN, REPS, ANIMS, A, SEQ, compose, derive, poseAt, FW, FH, OX, OY, createLifeMotion };\n',
        encoding='utf-8',
    )
    print(f'Extracted shared pose engine to {target.relative_to(ROOT)}')


if __name__ == '__main__':
    compile_motion()
